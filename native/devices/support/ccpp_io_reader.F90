    if (.not.associated(read_char_callback)) then
      errcode=95; errmsg="Python NetCDF character callback is not registered"; return
    end if
    errcode=read_char_callback(this%handle,varname,len_trim(varname),6,subset, &
         c_start,c_count,c_loc(var),int(len(var)*size(var),c_size_t),errmsg,len(errmsg))
  end subroutine callback_get_var_char_5d

end module pycam_netcdf_callback_reader

