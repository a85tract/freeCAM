! Python-owned provider for the namelist module generated by CAM's build.
module musica_ccpp_namelist
  use iso_c_binding, only: c_char, c_int
  implicit none
  private

  character(len=512), public :: micm_solver_type = "Rosenbrock"
  character(len=512), public :: filename_of_micm_configuration = "none"
  character(len=512), public :: filename_of_tuvx_configuration = "none"
  character(len=512), public :: filename_of_tuvx_micm_mapping_configuration = "none"

  public :: pycam_musica_configure_v1

contains

  integer(c_int) function pycam_musica_configure_v1( &
      solver, solver_length, micm, micm_length, tuvx, tuvx_length, &
      mapping, mapping_length) result(status) &
      bind(C, name="pycam_musica_configure_v1")
    character(kind=c_char), intent(in) :: solver(*), micm(*), tuvx(*), mapping(*)
    integer(c_int), value, intent(in) :: solver_length, micm_length
    integer(c_int), value, intent(in) :: tuvx_length, mapping_length

    call copy_c_string(solver, solver_length, micm_solver_type)
    call copy_c_string(micm, micm_length, filename_of_micm_configuration)
    call copy_c_string(tuvx, tuvx_length, filename_of_tuvx_configuration)
    call copy_c_string(mapping, mapping_length, &
                       filename_of_tuvx_micm_mapping_configuration)
    status = 0_c_int
  end function pycam_musica_configure_v1

  subroutine copy_c_string(source, source_length, target)
    character(kind=c_char), intent(in) :: source(*)
    integer(c_int), value, intent(in) :: source_length
    character(len=*), intent(out) :: target
    integer :: index, count

    target = ""
    count = min(int(source_length), len(target))
    do index = 1, count
      target(index:index) = achar(iachar(source(index)))
    end do
  end subroutine copy_c_string

end module musica_ccpp_namelist
