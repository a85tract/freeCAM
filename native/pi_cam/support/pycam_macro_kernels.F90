  subroutine macrop_detrain_partition( &
         ncol, top_lev, ixcldliq, ixcldice, ixnumliq, ixnumice, nwset, &
         iatype_liq, iatype_ice, do_detrain, cu_det_st, do_wtrc_detrain, &
         gravit, latice, cpair, t, pdel, dlf, dlf2, wtdlf, ptend_s, ptend_q, &
         det_s, det_ice, dlf_T, dlf_qv, dlf_ql, dlf_qi, dlf_nl, dlf_ni, &
         dpdlfliq, dpdlfice, shdlfliq, shdlfice, dpdlft, shdlft)

   integer,  intent(in)    :: ncol, top_lev, nwset
   integer,  intent(in)    :: ixcldliq, ixcldice, ixnumliq, ixnumice
   integer,  intent(in)    :: iatype_liq(nwset), iatype_ice(nwset)
   logical,  intent(in)    :: do_detrain, cu_det_st, do_wtrc_detrain
   real(r8), intent(in)    :: gravit, latice, cpair
   real(r8), intent(in)    :: t(pcols,pver), pdel(pcols,pver)
   real(r8), intent(in)    :: dlf(pcols,pver), dlf2(pcols,pver)
   real(r8), intent(in)    :: wtdlf(pcols,pver,nwset)
   real(r8), intent(inout) :: ptend_s(pcols,pver)
   real(r8), intent(inout) :: ptend_q(pcols,pver,pcnst)
   real(r8), intent(out)   :: det_s(pcols), det_ice(pcols)
   ! Zeroed by the caller and written only under cu_det_st, so these
   ! carry their incoming values out when that branch is not taken.
   real(r8), intent(inout) :: dlf_T(pcols,pver), dlf_qv(pcols,pver)
   real(r8), intent(inout) :: dlf_ql(pcols,pver), dlf_qi(pcols,pver)
   real(r8), intent(inout) :: dlf_nl(pcols,pver), dlf_ni(pcols,pver)
   real(r8), intent(out)   :: dpdlfliq(pcols,pver), dpdlfice(pcols,pver)
   real(r8), intent(out)   :: shdlfliq(pcols,pver), shdlfice(pcols,pver)
   real(r8), intent(out)   :: dpdlft(pcols,pver), shdlft(pcols,pver)

   integer  :: i, k, m
   real(r8) :: dum1

      det_s(:)   = 0._r8
      det_ice(:) = 0._r8

      dpdlfliq = 0._r8
      dpdlfice = 0._r8
      shdlfliq = 0._r8
      shdlfice = 0._r8
      dpdlft   = 0._r8
      shdlft   = 0._r8

      do k = top_lev, pver
      do i = 1, ncol
         if( t(i,k) > 268.15_r8 ) then
             dum1 = 0.0_r8
         elseif( t(i,k) < 238.15_r8 ) then
             dum1 = 1.0_r8
         else
             dum1 = ( 268.15_r8 - t(i,k) ) / 30._r8
         endif

        ! If detrainment was done elsewhere, still update the variables used for output
        ! assuming that the temperature split between liquid and ice is the same as assumed
        ! here.
        if (do_detrain) then
         ptend_q(i,k,ixcldliq) = dlf(i,k) * ( 1._r8 - dum1 )
         ptend_q(i,k,ixcldice) = dlf(i,k) * dum1
       ! dum2                      = dlf(i,k) * ( 1._r8 - dum1 )
         ptend_q(i,k,ixnumliq) = 3._r8 * ( max(0._r8, ( dlf(i,k) - dlf2(i,k) )) * ( 1._r8 - dum1 ) ) / &
              (4._r8*3.14_r8* 8.e-6_r8**3*997._r8) + & ! Deep    Convection
              3._r8 * (                         dlf2(i,k)    * ( 1._r8 - dum1 ) ) / &
              (4._r8*3.14_r8*10.e-6_r8**3*997._r8)     ! Shallow Convection 
       ! dum2                      = dlf(i,k) * dum1
         ptend_q(i,k,ixnumice) = 3._r8 * ( max(0._r8, ( dlf(i,k) - dlf2(i,k) )) *  dum1 ) / &
              (4._r8*3.14_r8*25.e-6_r8**3*500._r8) + & ! Deep    Convection
              3._r8 * (                         dlf2(i,k)    *  dum1 ) / &
              (4._r8*3.14_r8*50.e-6_r8**3*500._r8)     ! Shallow Convection
         ptend_s(i,k)          = dlf(i,k) * dum1 * latice
        else 
           ptend_q(i,k,ixcldliq) = 0._r8
           ptend_q(i,k,ixcldice) = 0._r8
           ptend_q(i,k,ixnumliq) = 0._r8
           ptend_q(i,k,ixnumice) = 0._r8
           ptend_s(i,k)          = 0._r8
        end if
    

       ! Only rliq is saved from deep convection, which is the reserved liquid.  We need to keep
       !   track of the integrals of ice and static energy that is effected from conversion to ice
       !   so that the energy checker doesn't complain.
         det_s(i)                  = det_s(i) + ptend_s(i,k)*pdel(i,k)/gravit
         det_ice(i)                = det_ice(i) - ptend_q(i,k,ixcldice)*pdel(i,k)/gravit      

       ! Targetted detrainment of convective liquid water either directly into the
       ! existing liquid stratus or into the environment. 

         !water tracers:
         !NOTE:  This assumes no fractionation during freezing/melting. - JN
         if (do_wtrc_detrain) then
           do m=1,nwset
             ptend_q(i,k,iatype_liq(m)) = wtdlf(i,k,m) * (1._r8 - dum1)
             ptend_q(i,k,iatype_ice(m)) = wtdlf(i,k,m) * dum1
           end do
         end if

         if( cu_det_st ) then
             dlf_T(i,k)  = ptend_s(i,k)/cpair
             dlf_qv(i,k) = 0._r8
             dlf_ql(i,k) = ptend_q(i,k,ixcldliq)
             dlf_qi(i,k) = ptend_q(i,k,ixcldice)
             dlf_nl(i,k) = ptend_q(i,k,ixnumliq)
             dlf_ni(i,k) = ptend_q(i,k,ixnumice)         
             ptend_q(i,k,ixcldliq) = 0._r8
             ptend_q(i,k,ixcldice) = 0._r8
             ptend_q(i,k,ixnumliq) = 0._r8
             ptend_q(i,k,ixnumice) = 0._r8
             ptend_s(i,k)          = 0._r8
             dpdlfliq(i,k)             = 0._r8
             dpdlfice(i,k)             = 0._r8
             shdlfliq(i,k)             = 0._r8
             shdlfice(i,k)             = 0._r8
             dpdlft  (i,k)             = 0._r8
             shdlft  (i,k)             = 0._r8
          else
             dpdlfliq(i,k) = ( dlf(i,k) - dlf2(i,k) ) * ( 1._r8 - dum1 )
             dpdlfice(i,k) = ( dlf(i,k) - dlf2(i,k) ) * ( dum1 )
             shdlfliq(i,k) = dlf2(i,k) * ( 1._r8 - dum1 )
             shdlfice(i,k) = dlf2(i,k) * ( dum1 )
             dpdlft  (i,k) = ( dlf(i,k) - dlf2(i,k) ) * dum1 * latice/cpair
             shdlft  (i,k) = dlf2(i,k) * dum1 * latice/cpair
         endif
      end do
      end do

  end subroutine macrop_detrain_partition

  subroutine macrop_clear_fraction( &
         ncol, top_lev, concld, alst, ast, clrw_old, clri_old)

   integer,  intent(in)  :: ncol, top_lev
   real(r8), intent(in)  :: concld(pcols,pver), alst(pcols,pver), ast(pcols,pver)
   real(r8), intent(out) :: clrw_old(pcols,pver), clri_old(pcols,pver)

   integer :: i, k

      clrw_old(:ncol,:top_lev-1) = 0._r8
      clri_old(:ncol,:top_lev-1) = 0._r8
      do k = top_lev, pver
         do i = 1, ncol
            clrw_old(i,k) = max( 0._r8, min( 1._r8, 1._r8 - concld(i,k) - alst(i,k) ) )      
            clri_old(i,k) = max( 0._r8, min( 1._r8, 1._r8 - concld(i,k) -  ast(i,k) ) )      
         end do
      end do

  end subroutine macrop_clear_fraction

  subroutine macrop_advective_forcing( &
         ncol, top_lev, nstep, rdtime, t, q, qc, qi, nc, ni, CC_T, CC_qv, &
         CC_ql, CC_qi, CC_nl, CC_ni, CC_qlst, tcwat, qcwat, lcwat, iccwat, &
         nlwat, niwat, ttend, qtend, ltend, itend, nltend, nitend, lmitend, &
         t_inout, qv_inout, ql_inout, qi_inout, nl_inout, ni_inout)

   integer,  intent(in)    :: ncol, top_lev, nstep
   real(r8), intent(in)    :: rdtime
   real(r8), intent(in)    :: t(pcols,pver), q(pcols,pver,pcnst)
   real(r8), intent(in)    :: qc(pcols,pver), qi(pcols,pver)
   real(r8), intent(in)    :: nc(pcols,pver), ni(pcols,pver)
   ! At the first step these are overwritten from the state, so they
   ! are in/out even though every later step only reads them.
   real(r8), intent(inout) :: tcwat(pcols,pver), qcwat(pcols,pver)
   real(r8), intent(inout) :: lcwat(pcols,pver), iccwat(pcols,pver)
   real(r8), intent(inout) :: nlwat(pcols,pver), niwat(pcols,pver)
   real(r8), intent(inout) :: CC_T(pcols,pver), CC_qv(pcols,pver)
   real(r8), intent(inout) :: CC_ql(pcols,pver), CC_qi(pcols,pver)
   real(r8), intent(inout) :: CC_nl(pcols,pver), CC_ni(pcols,pver)
   real(r8), intent(inout) :: CC_qlst(pcols,pver)
   real(r8), intent(out)   :: ttend(pcols,pver), qtend(pcols,pver)
   real(r8), intent(out)   :: ltend(pcols,pver), itend(pcols,pver)
   real(r8), intent(out)   :: nltend(pcols,pver), nitend(pcols,pver)
   real(r8), intent(out)   :: lmitend(pcols,pver)
   real(r8), intent(out)   :: t_inout(pcols,pver), qv_inout(pcols,pver)
   real(r8), intent(out)   :: ql_inout(pcols,pver), qi_inout(pcols,pver)
   real(r8), intent(out)   :: nl_inout(pcols,pver), ni_inout(pcols,pver)

      if( nstep .le. 1 ) then
          tcwat(:ncol,:)   = t(:ncol,:)
          qcwat(:ncol,:)   = q(:ncol,:,1)
          lcwat(:ncol,:)   = qc(:ncol,:) + qi(:ncol,:)
          iccwat(:ncol,:)  = qi(:ncol,:)
          nlwat(:ncol,:)   = nc(:ncol,:)
          niwat(:ncol,:)   = ni(:ncol,:)
          ttend(:ncol,:)   = 0._r8
          qtend(:ncol,:)   = 0._r8
          ltend(:ncol,:)   = 0._r8
          itend(:ncol,:)   = 0._r8
          nltend(:ncol,:)  = 0._r8
          nitend(:ncol,:)  = 0._r8
          CC_T(:ncol,:)    = 0._r8
          CC_qv(:ncol,:)   = 0._r8
          CC_ql(:ncol,:)   = 0._r8
          CC_qi(:ncol,:)   = 0._r8
          CC_nl(:ncol,:)   = 0._r8
          CC_ni(:ncol,:)   = 0._r8
          CC_qlst(:ncol,:) = 0._r8
      else
          ttend(:ncol,top_lev:pver)   = ( t(:ncol,top_lev:pver)   -  tcwat(:ncol,top_lev:pver)) * rdtime &
               - CC_T(:ncol,top_lev:pver) 
          qtend(:ncol,top_lev:pver)   = ( q(:ncol,top_lev:pver,1) -  qcwat(:ncol,top_lev:pver)) * rdtime &
               - CC_qv(:ncol,top_lev:pver)
          ltend(:ncol,top_lev:pver)   = ( qc(:ncol,top_lev:pver) + qi(:ncol,top_lev:pver) - lcwat(:ncol,top_lev:pver) ) * rdtime &
               - (CC_ql(:ncol,top_lev:pver) + CC_qi(:ncol,top_lev:pver))
          itend(:ncol,top_lev:pver)   = ( qi(:ncol,top_lev:pver)         - iccwat(:ncol,top_lev:pver)) * rdtime &
               - CC_qi(:ncol,top_lev:pver)
          nltend(:ncol,top_lev:pver)  = ( nc(:ncol,top_lev:pver)         -  nlwat(:ncol,top_lev:pver)) * rdtime &
               - CC_nl(:ncol,top_lev:pver)
          nitend(:ncol,top_lev:pver)  = ( ni(:ncol,top_lev:pver)         -  niwat(:ncol,top_lev:pver)) * rdtime &
               - CC_ni(:ncol,top_lev:pver)
      endif
      lmitend(:ncol,top_lev:pver) = ltend(:ncol,top_lev:pver) - itend(:ncol,top_lev:pver)

      t_inout(:ncol,top_lev:pver)  =  tcwat(:ncol,top_lev:pver) 
      qv_inout(:ncol,top_lev:pver) =  qcwat(:ncol,top_lev:pver)
      ql_inout(:ncol,top_lev:pver) =  lcwat(:ncol,top_lev:pver) - iccwat(:ncol,top_lev:pver)
      qi_inout(:ncol,top_lev:pver) = iccwat(:ncol,top_lev:pver)
      nl_inout(:ncol,top_lev:pver) =  nlwat(:ncol,top_lev:pver)
      ni_inout(:ncol,top_lev:pver) =  niwat(:ncol,top_lev:pver)

  end subroutine macrop_advective_forcing

  subroutine macrop_kernel_to_ptend( &
         ncol, top_lev, ixcldliq, ixcldice, ixnumliq, ixnumice, do_cldice, &
         do_cldliq, tlat, qvlat, qcten, qiten, ncten, niten, ptend_s, &
         ptend_q, status)

   integer,  intent(in)    :: ncol, top_lev
   integer,  intent(in)    :: ixcldliq, ixcldice, ixnumliq, ixnumice
   logical,  intent(in)    :: do_cldice, do_cldliq
   real(r8), intent(in)    :: tlat(pcols,pver), qvlat(pcols,pver)
   real(r8), intent(in)    :: qcten(pcols,pver), qiten(pcols,pver)
   real(r8), intent(in)    :: ncten(pcols,pver), niten(pcols,pver)
   real(r8), intent(inout) :: ptend_s(pcols,pver)
   real(r8), intent(inout) :: ptend_q(pcols,pver,pcnst)
   ! The original calls endrun on each of these four; a routine Python
   ! drives reports instead, and the caller decides to stop.
   integer,  intent(out)   :: status

   integer :: i, k

   status = 0

      do k = top_lev, pver
         do i = 1, ncol
            ptend_s(i,k)          =  tlat(i,k)
            ptend_q(i,k,1)        = qvlat(i,k)
            ptend_q(i,k,ixcldliq) = qcten(i,k)
            ptend_q(i,k,ixcldice) = qiten(i,k)
            ptend_q(i,k,ixnumliq) = ncten(i,k)
            ptend_q(i,k,ixnumice) = niten(i,k)

            ! Check to make sure that the macrophysics code is respecting the flags that control
            ! whether cldwat should be prognosing cloud ice and cloud liquid or not.
            if ((.not. do_cldice) .and. (qiten(i,k) /= 0.0_r8)) then 
               status = 1
                 
            end if
            if ((.not. do_cldice) .and. (niten(i,k) /= 0.0_r8)) then 
               status = 2
                 
            end if

            if ((.not. do_cldliq) .and. (qcten(i,k) /= 0.0_r8)) then 
               status = 1
                 
            end if
            if ((.not. do_cldliq) .and. (ncten(i,k) /= 0.0_r8)) then 
               status = 1
                 
            end if
         end do
      end do

  end subroutine macrop_kernel_to_ptend

  subroutine macrop_tracer_rate_split( &
         ncol, top_lev, qcten, qiten, pqctn, nqctn, pqitn, nqitn)

   integer,  intent(in)  :: ncol, top_lev
   real(r8), intent(in)  :: qcten(pcols,pver), qiten(pcols,pver)
   real(r8), intent(out) :: pqctn(pcols,pver), nqctn(pcols,pver)
   real(r8), intent(out) :: pqitn(pcols,pver), nqitn(pcols,pver)

   integer :: i, k

        pqctn(:,top_lev:) = 0._r8
        nqctn(:,top_lev:) = 0._r8
        pqitn(:,top_lev:) = 0._r8
        nqitn(:,top_lev:) = 0._r8

        !split into positive and negative tendencies - JN
        do i=1,ncol
          do k=top_lev,pver
            if(qcten(i,k) .lt. 0._r8) then
              nqctn(i,k) = qcten(i,k) 
            else
              pqctn(i,k) = qcten(i,k)
            end if
            if(qiten(i,k) .lt. 0._r8) then
              nqitn(i,k) = qiten(i,k)
            else
              pqitn(i,k) = qiten(i,k)
            end if  
          end do
        end do

  end subroutine macrop_tracer_rate_split

  subroutine macrop_cloud_mixing_ratio( &
         ncol, top_lev, ixcldliq, ixcldice, q, cld, mr_ccliq, mr_ccice, &
         mr_lsliq, mr_lsice)

   integer,  intent(in)  :: ncol, top_lev, ixcldliq, ixcldice
   real(r8), intent(in)  :: q(pcols,pver,pcnst), cld(pcols,pver)
   real(r8), intent(out) :: mr_ccliq(pcols,pver), mr_ccice(pcols,pver)
   real(r8), intent(out) :: mr_lsliq(pcols,pver), mr_lsice(pcols,pver)

   integer :: i, k

      mr_ccliq = 0._r8   !! not seen by radiation, so setting to 0 
      mr_ccice = 0._r8   !! not seen by radiation, so setting to 0
      mr_lsliq = 0._r8
      mr_lsice = 0._r8

      do k=top_lev,pver
         do i=1,ncol
            if (cld(i,k) .gt. 0._r8) then
               mr_lsliq(i,k) = q(i,k,ixcldliq)
               mr_lsice(i,k) = q(i,k,ixcldice)
            else
               mr_lsliq(i,k) = 0._r8
               mr_lsice(i,k) = 0._r8
            end if
         end do
      end do

  end subroutine macrop_cloud_mixing_ratio

  subroutine macrop_save_equilibrium( &
         ncol, top_lev, ixcldliq, ixcldice, ixnumliq, ixnumice, tmelt, t, q, &
         tcwat, qcwat, lcwat, iccwat, nlwat, niwat, cldsice)

   integer,  intent(in)  :: ncol, top_lev
   integer,  intent(in)  :: ixcldliq, ixcldice, ixnumliq, ixnumice
   real(r8), intent(in)  :: tmelt
   real(r8), intent(in)  :: t(pcols,pver), q(pcols,pver,pcnst)
   real(r8), intent(out) :: tcwat(pcols,pver), qcwat(pcols,pver)
   real(r8), intent(out) :: lcwat(pcols,pver), iccwat(pcols,pver)
   real(r8), intent(out) :: nlwat(pcols,pver), niwat(pcols,pver)
   real(r8), intent(out) :: cldsice(pcols,pver)

   integer :: k

      cldsice = 0._r8
      do k = top_lev, pver
         tcwat(:ncol,k)  = t(:ncol,k)
         qcwat(:ncol,k)  = q(:ncol,k,1)
         lcwat(:ncol,k)  = q(:ncol,k,ixcldliq) + q(:ncol,k,ixcldice)
         iccwat(:ncol,k) = q(:ncol,k,ixcldice)
         nlwat(:ncol,k)  = q(:ncol,k,ixnumliq)
         niwat(:ncol,k)  = q(:ncol,k,ixnumice)
         cldsice(:ncol,k) = lcwat(:ncol,k) * min(1.0_r8, max(0.0_r8, (tmelt - tcwat(:ncol,k)) / 20._r8))
      end do


  end subroutine macrop_save_equilibrium

