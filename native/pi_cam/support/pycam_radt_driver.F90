           ! channels as a diagnostic to compare to TOV/MSU satellite data.
           ! Done if dohirs set to .true. at time step frequency ihirsfq

           nstep = get_nstep()

           if ( dohirs .and. (mod(nstep-1,ihirsfq) .eq. 0) ) then

