  subroutine micro_liquid_size( &
         ngrdcol, top_lev, mincld, qsmall, icwmrst_grid, rho_grid, nc_grid, &
         liqcldf_grid, mu_grid, lambdac_grid, rel_fn_grid, ncic_grid, &
         rel_grid)

   integer,  intent(in) :: ngrdcol
   integer,  intent(in) :: top_lev
   real(r8), intent(in) :: mincld
   real(r8), intent(in) :: qsmall
   real(r8), intent(in) :: icwmrst_grid(pcols,pver)
   real(r8), intent(in) :: rho_grid(pcols,pver)
   real(r8), intent(in) :: nc_grid(pcols,pver)
   real(r8), intent(in) :: liqcldf_grid(pcols,pver)
   real(r8), intent(inout) :: mu_grid(pcols,pver)
   real(r8), intent(inout) :: lambdac_grid(pcols,pver)
   real(r8), intent(inout) :: rel_fn_grid(pcols,pver)
   real(r8), intent(inout) :: ncic_grid(pcols,pver)
   real(r8), intent(inout) :: rel_grid(pcols,pver)

      mu_grid = 0._r8
      lambdac_grid = 0._r8
      rel_fn_grid = 10._r8

      ncic_grid = 1.e8_r8

      call size_dist_param_liq(mg_liq_props, icwmrst_grid(:ngrdcol,top_lev:), &
           ncic_grid(:ngrdcol,top_lev:), rho_grid(:ngrdcol,top_lev:), &
           mu_grid(:ngrdcol,top_lev:), lambdac_grid(:ngrdcol,top_lev:))

      where (icwmrst_grid(:ngrdcol,top_lev:) > qsmall)
         rel_fn_grid(:ngrdcol,top_lev:) = &
              (mu_grid(:ngrdcol,top_lev:) + 3._r8)/ &
              lambdac_grid(:ngrdcol,top_lev:)/2._r8 * 1.e6_r8
      end where

      ! Effective radius for cloud liquid, and size parameters
      ! mu_grid and lambdac_grid.
      mu_grid = 0._r8
      lambdac_grid = 0._r8
      rel_grid = 10._r8

      ! Calculate ncic on the grid
      ncic_grid(:ngrdcol,top_lev:) = nc_grid(:ngrdcol,top_lev:) / &
           max(mincld,liqcldf_grid(:ngrdcol,top_lev:))

      call size_dist_param_liq(mg_liq_props, icwmrst_grid(:ngrdcol,top_lev:), &
           ncic_grid(:ngrdcol,top_lev:), rho_grid(:ngrdcol,top_lev:), &
           mu_grid(:ngrdcol,top_lev:), lambdac_grid(:ngrdcol,top_lev:))

      where (icwmrst_grid(:ngrdcol,top_lev:) >= qsmall)
         rel_grid(:ngrdcol,top_lev:) = &
              (mu_grid(:ngrdcol,top_lev:) + 3._r8) / &
              lambdac_grid(:ngrdcol,top_lev:)/2._r8 * 1.e6_r8
      elsewhere
         ! Deal with the fact that size_dist_param_liq sets mu_grid to -100
         ! wherever there is no cloud.
         mu_grid(:ngrdcol,top_lev:) = 0._r8
      end where

  end subroutine micro_liquid_size

  subroutine micro_ice_and_precip_size( &
         ngrdcol, top_lev, mincld, qsmall, qrout_grid, nrout_grid, &
