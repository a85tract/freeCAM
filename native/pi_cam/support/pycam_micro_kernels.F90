  subroutine micro_in_cloud_quantities( &
         ncol, top_lev, ixcldliq, ixcldice, ixnumliq, ixnumice, mincld, &
         gravit, q_loc, pmid_loc, t_loc, pdel_loc, icecldf, liqcldf, ast, &
         cld, concld, qsout, icimrst, icwmrst, icinc, icwnc, iciwpst, &
         iclwpst, cldfsnow, icswp)

   integer,  intent(in) :: ncol
   integer,  intent(in) :: top_lev
   integer,  intent(in) :: ixcldliq
   integer,  intent(in) :: ixcldice
   integer,  intent(in) :: ixnumliq
   integer,  intent(in) :: ixnumice
   real(r8), intent(in) :: mincld
   real(r8), intent(in) :: gravit
   real(r8), intent(in) :: q_loc(pcols,pver,pcnst)
   real(r8), intent(in) :: pmid_loc(pcols,pver)
   real(r8), intent(in) :: t_loc(pcols,pver)
   real(r8), intent(in) :: pdel_loc(pcols,pver)
   real(r8), intent(in) :: icecldf(pcols,pver)
   real(r8), intent(in) :: liqcldf(pcols,pver)
   real(r8), intent(in) :: ast(pcols,pver)
   real(r8), intent(in) :: cld(pcols,pver)
   real(r8), intent(in) :: concld(pcols,pver)
   real(r8), intent(in) :: qsout(pcols,pver)
   real(r8), intent(inout) :: icimrst(pcols,pver)
   real(r8), intent(inout) :: icwmrst(pcols,pver)
   real(r8), intent(inout) :: icinc(pcols,pver)
   real(r8), intent(inout) :: icwnc(pcols,pver)
   real(r8), intent(inout) :: iciwpst(pcols,pver)
   real(r8), intent(inout) :: iclwpst(pcols,pver)
   real(r8), intent(inout) :: cldfsnow(pcols,pver)
   real(r8), intent(inout) :: icswp(pcols,pver)

   integer :: i, k

      do k = top_lev, pver
         do i = 1, ncol
            ! Limits for in-cloud mixing ratios consistent with MG microphysics
            ! in-cloud mixing ratio maximum limit of 0.005 kg/kg
            icimrst(i,k)   = min( q_loc(i,k,ixcldice) / max(mincld,icecldf(i,k)),0.005_r8 )
            icwmrst(i,k)   = min( q_loc(i,k,ixcldliq) / max(mincld,liqcldf(i,k)),0.005_r8 )
            icinc(i,k)     = q_loc(i,k,ixnumice) / max(mincld,icecldf(i,k)) * &
                 pmid_loc(i,k) / (287.15_r8*t_loc(i,k))
            icwnc(i,k)     = q_loc(i,k,ixnumliq) / max(mincld,liqcldf(i,k)) * &
                 pmid_loc(i,k) / (287.15_r8*t_loc(i,k))
            ! Calculate micro_mg_cam cloud water paths in each layer
            ! Note: uses stratiform cloud fraction!
            iciwpst(i,k)   = min(q_loc(i,k,ixcldice)/max(mincld,ast(i,k)),0.005_r8) * pdel_loc(i,k) / gravit
            iclwpst(i,k)   = min(q_loc(i,k,ixcldliq)/max(mincld,ast(i,k)),0.005_r8) * pdel_loc(i,k) / gravit

            ! ------------------------------ !
            ! Adjust cloud fraction for snow !
            ! ------------------------------ !
            cldfsnow(i,k) = cld(i,k)
            ! If cloud and only ice ( no convective cloud or ice ), then set to 0.
            if( ( cldfsnow(i,k) .gt. 1.e-4_r8 ) .and. &
               ( concld(i,k)   .lt. 1.e-4_r8 ) .and. &
               ( q_loc(i,k,ixcldliq) .lt. 1.e-10_r8 ) ) then
               cldfsnow(i,k) = 0._r8
            end if
            ! If no cloud and snow, then set to 0.25
            if( ( cldfsnow(i,k) .le. 1.e-4_r8 ) .and. ( qsout(i,k) .gt. 1.e-6_r8 ) ) then
               cldfsnow(i,k) = 0.25_r8
            end if
            ! Calculate in-cloud snow water path
            icswp(i,k) = qsout(i,k) / max( mincld, cldfsnow(i,k) ) * pdel_loc(i,k) / gravit
         end do
      end do

  end subroutine micro_in_cloud_quantities

  subroutine micro_split_signs( &
         ncol, top_lev, cmeiout_grid, meltso, meltso_grid, pcmei_grid, &
         ncmei_grid, pmelts_grid, nmelts_grid)

   integer,  intent(in) :: ncol
   integer,  intent(in) :: top_lev
   real(r8), intent(in) :: cmeiout_grid(pcols,pver)
   real(r8), intent(in) :: meltso(pcols,pver)
   real(r8), intent(in) :: meltso_grid(pcols,pver)
   real(r8), intent(inout) :: pcmei_grid(pcols,pver)
   real(r8), intent(inout) :: ncmei_grid(pcols,pver)
   real(r8), intent(inout) :: pmelts_grid(pcols,pver)
   real(r8), intent(inout) :: nmelts_grid(pcols,pver)

   integer :: i, k

            pcmei_grid(:,top_lev:) = 0._r8
            ncmei_grid(:,top_lev:) = 0._r8
            pmelts_grid(:,top_lev:) = 0._r8
            nmelts_grid(:,top_lev:) = 0._r8

            !split into positive and negative tendencies - JN
            do i=1,ncol
              do k=top_lev,pver
                if(cmeiout_grid(i,k) .lt. 0._r8) then
                  ncmei_grid(i,k) = cmeiout_grid(i,k) !sublimation (ice-dependent)
                else
                  pcmei_grid(i,k) = cmeiout_grid(i,k) !deposition (vapor-dependent)
                end if
                if(meltso(i,k) .lt. 0._r8) then
                  nmelts_grid(i,k) = meltso_grid(i,k)
                else
                  pmelts_grid(i,k) = meltso_grid(i,k)
                end if
              end do
            end do

  end subroutine micro_split_signs

