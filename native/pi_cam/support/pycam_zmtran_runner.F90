    created = .false.
    pc = pc_idle
    status = 0_c_int
  end function pycam_zmtran_destroy_v1

  ! ------------------------------------------------------------------ !
  ! The state machine
  ! ------------------------------------------------------------------ !

  subroutine advance(event)
    integer(c_int), intent(out) :: event
    do
      select case (pc)
      case (pc_chunk_begin)
        if (lchnk > endchunk) then
          pc = pc_idle
          event = ev_done
          return
        end if
        call glue_enter(lchnk)
        pc = pc_glue_piece_1_1
      case (pc_chunk_end)
        lchnk = lchnk + 1
        pc = pc_chunk_begin
      case (pc_glue_piece_4_1)
        call glue_piece_4()
        pc = pc_chunk_end
      case (pc_glue_piece_3_1)
        call glue_piece_3()
        pc = pc_glue_piece_4_1
      case (pc_glue_piece_2_1)
        call glue_piece_2()
        pc = pc_glue_piece_3_1
      case (pc_zm2_piece_3_1)
        call zm2_piece_3()
        pc = pc_leave_zm2_1
      case (pc_before_convtran_1)
        if (replace(1)) then
          token = token + 1_c_int
          pc = pc_at_convtran
          event = ev_needs_kernel
          return
        end if
        call convtran_original()
        pc = pc_after_convtran
      case (pc_at_convtran)
        last_error = 'zmtran is paused; only resume continues it'
        event = ev_error
        return
      case (pc_after_convtran)
        call_index = call_index + 1_c_int
        pc = pc_zm2_piece_3_1
      case (pc_zm2_piece_2_1)
        call zm2_piece_2()
        pc = pc_before_convtran_1
      case (pc_if_1)
        if (any(ptend%lq(:))) then
          pc = pc_zm2_piece_2_1
        else
          pc = pc_leave_zm2_1
        end if
      case (pc_zm2_piece_1_1)
        call zm2_piece_1()
        pc = pc_if_1
      case (pc_leave_zm2_1)
        pc = pc_leave_deep2_1
      case (pc_enter_zm2_1)
        call deep2_bind_zm2()
        pc = pc_zm2_piece_1_1
      case (pc_deep2_piece_1_1)
        call deep2_piece_1()
        pc = pc_leave_deep2_1
      case (pc_if_2)
        if ( deep_scheme .eq. 'ZM' ) then
          pc = pc_enter_zm2_1
        else
          pc = pc_deep2_piece_1_1
        end if
      case (pc_leave_deep2_1)
        pc = pc_glue_piece_2_1
      case (pc_enter_deep2_1)
        call glue_bind_deep2()
        pc = pc_if_2
      case (pc_glue_piece_1_1)
        call glue_piece_1()
        pc = pc_enter_deep2_1
      case default
        last_error = 'zmtran program counter is corrupt'
        event = ev_error
        return
      end select
    end do
  end subroutine advance

end module pycam_zmtran_runner
