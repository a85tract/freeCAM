    case (pc_at_convtran)
      call convtran_frame(ptrs, ndims, shapes, dtypes, intents, ncol_out)
      kernel = kernel_convtran
    case default
      last_error = 'zmtran is not paused; there is no frame'; status = 2_c_int; return
    end select
