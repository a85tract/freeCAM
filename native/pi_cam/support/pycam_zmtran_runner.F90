  integer(c_int) function pycam_zmtran_original_v1(context, kernel) bind(C, name='pycam_zmtran_original_v1') result(status)
    ! Run the original call on the paused frame: the validation gate's
    ! replacement, exercising the pause, the frame and the resume.
    integer(c_int), value, intent(in) :: context, kernel
    status = 1_c_int
    if (.not. created .or. context /= context_id) then
      last_error = 'no zmtran context'; return
    end if
    select case (pc)
    case (pc_at_convtran)
      if (kernel /= kernel_convtran) then
        last_error = 'zmtran is paused on convtran, not on the kernel asked for'; status = 3_c_int; return
      end if
