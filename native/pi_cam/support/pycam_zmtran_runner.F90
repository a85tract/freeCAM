    lchnk = begchunk
    pc = pc_chunk_begin
    call advance(event)
    status = 0_c_int
  end function pycam_zmtran_start_v1

  integer(c_int) function pycam_zmtran_resume_v1(context, kernel, token_in, event) bind(C, name='pycam_zmtran_resume_v1') result(status)
    integer(c_int), value, intent(in) :: context, kernel, token_in
    integer(c_int), intent(out) :: event
    event = ev_error
    status = 1_c_int
    if (.not. created .or. context /= context_id) then
      last_error = 'no zmtran context'; return
    end if
    if (token_in /= token) then
      last_error = 'stale resume: the frame token does not match the pause'; status = 4_c_int; return
    end if
    select case (pc)
    case (pc_at_convtran)
      if (kernel /= kernel_convtran) then
        last_error = 'zmtran is paused on convtran, not on the kernel resumed'; status = 3_c_int; return
      end if
      pc = pc_after_convtran
    case default
      last_error = 'zmtran is not paused'; status = 2_c_int; return
    end select
    token = token + 1_c_int
    call advance(event)
    status = 0_c_int
  end function pycam_zmtran_resume_v1

  integer(c_int) function pycam_zmtran_frame_v1(context, kernel, index_out, lchnk_out, ncol_out, &
