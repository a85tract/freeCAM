        if (replace(1)) then
          token = token + 1_c_int
          pc = pc_at_gas_phase_chemdr
          event = ev_needs_kernel
          return
        end if
        call gas_phase_chemdr_original()
        pc = pc_after_gas_phase_chemdr
      case (pc_at_gas_phase_chemdr)
        last_error = 'chem is paused; only resume continues it'
        event = ev_error
        return
      case (pc_after_gas_phase_chemdr)
        call_index = call_index + 1_c_int
        pc = pc_driver_piece_2_1
      case (pc_driver_piece_1_1)
        call driver_piece_1()
        select case (driver_flow)
        case (3)
          driver_flow = 0
          pc = pc_leave_driver_1
        case default
          pc = pc_before_gas_phase_chemdr_1
        end select
      case (pc_leave_driver_1)
        pc = pc_glue_piece_1_1
      case (pc_enter_driver_1)
        call glue_bind_driver()
        pc = pc_driver_piece_1_1
      case (pc_if_1)
        if (chem_is_active()) then
          pc = pc_enter_driver_1
        else
          pc = pc_glue_piece_2_1
        end if
      case default
        last_error = 'chem program counter is corrupt'
        event = ev_error
        return
      end select
    end do
  end subroutine advance

