  subroutine advance(event)
    integer(c_int), intent(out) :: event
    do
      select case (pc)
      case (pc_chunk_begin)
        if (lchnk > endchunk) then
          pc = pc_idle
          event = ev_done
          return
        end if
        call glue_enter(lchnk)
        pc = pc_if_1
      case (pc_chunk_end)
        lchnk = lchnk + 1
        pc = pc_chunk_begin
      case (pc_glue_piece_2_1)
        call glue_piece_2()
        pc = pc_chunk_end
      case (pc_glue_piece_1_1)
        call glue_piece_1()
        pc = pc_glue_piece_2_1
