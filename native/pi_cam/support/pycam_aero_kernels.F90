module pycam_aero_kernels

  use shr_kind_mod, only: r8 => shr_kind_r8
  use ppgrid,       only: pcols, pver, pverp

  implicit none
  private

  real(r8), parameter :: rn_dst1 = 0.258e-6_r8
  real(r8), parameter :: rn_dst2 = 0.717e-6_r8
  real(r8), parameter :: rn_dst3 = 1.576e-6_r8
  real(r8), parameter :: rn_dst4 = 3.026e-6_r8

  public :: aero_initial_bins
  public :: aero_air_density
  public :: aero_subgrid_velocity
  public :: aero_liquid_fraction
  public :: aero_cloud_fraction_split
  public :: aero_npccn_from_mixnuc
  public :: aero_contact_freezing

contains

  subroutine aero_initial_bins( &
         ncol, npccn, nacon, rndst)

   integer,  intent(in) :: ncol
   real(r8), intent(inout) :: npccn(pcols,pver)
   real(r8), intent(inout) :: nacon(pcols,pver,4)
   real(r8), intent(inout) :: rndst(pcols,pver,4)

      npccn(1:ncol,1:pver)    = 0._r8  

      nacon(1:ncol,1:pver,:)  = 0._r8

      ! set default or fixed dust bins for contact freezing
      rndst(1:ncol,1:pver,1) = rn_dst1
      rndst(1:ncol,1:pver,2) = rn_dst2
      rndst(1:ncol,1:pver,3) = rn_dst3
      rndst(1:ncol,1:pver,4) = rn_dst4

  end subroutine aero_initial_bins

  subroutine aero_air_density( &
         ncol, top_lev, rair, pmid, t, rho)

   integer,  intent(in) :: ncol
   integer,  intent(in) :: top_lev
   real(r8), intent(in) :: rair
   real(r8), intent(in) :: pmid(pcols,pver)
   real(r8), intent(in) :: t(pcols,pver)
   real(r8), intent(inout) :: rho(pcols,pver)

   integer :: i, k

      do k = top_lev, pver
         do i = 1, ncol
            rho(i,k) = pmid(i,k)/(rair*t(i,k))
         end do
      end do

  end subroutine aero_air_density

  subroutine aero_subgrid_velocity( &
         ncol, top_lev, use_preexisting_ice, tke, wsub, wsubi)

   integer,  intent(in) :: ncol
   integer,  intent(in) :: top_lev
   logical,   intent(in) :: use_preexisting_ice
   real(r8), intent(in) :: tke(pcols,pverp)
   real(r8), intent(inout) :: wsub(pcols,pver)
   real(r8), intent(inout) :: wsubi(pcols,pver)

   integer :: i, k

      wsub(:ncol,:top_lev-1)  = 0.20_r8
      wsubi(:ncol,:top_lev-1) = 0.001_r8

      do k = top_lev, pver
         do i = 1, ncol

               wsub(i,k) = sqrt(0.5_r8*(tke(i,k) + tke(i,k+1))*(2._r8/3._r8))
               wsub(i,k) = min(wsub(i,k),10._r8)

               wsubi(i,k) = max(0.001_r8, wsub(i,k))
               if (.not. use_preexisting_ice) then
                  wsubi(i,k) = min(wsubi(i,k), 0.2_r8)
               endif

            wsub(i,k)  = max(0.20_r8, wsub(i,k))

         end do
      end do

  end subroutine aero_subgrid_velocity

  subroutine aero_liquid_fraction( &
         ncol, top_lev, mincld, ast, lcldm)

   integer,  intent(in) :: ncol
   integer,  intent(in) :: top_lev
   real(r8), intent(in) :: mincld
   real(r8), intent(in) :: ast(pcols,pver)
   real(r8), intent(inout) :: lcldm(pcols,pver)

   integer :: i, k

      do k = top_lev, pver
         do i = 1, ncol
            lcldm(i,k) = max(ast(i,k), mincld)
         end do
      end do

  end subroutine aero_liquid_fraction

  subroutine aero_cloud_fraction_split( &
         ncol, top_lev, qsmall, qc, qi, cldn, cldo, lcldn, lcldo)

   integer,  intent(in) :: ncol
   integer,  intent(in) :: top_lev
   real(r8), intent(in) :: qsmall
   real(r8), intent(in) :: qc(pcols,pver)
   real(r8), intent(in) :: qi(pcols,pver)
   real(r8), intent(in) :: cldn(pcols,pver)
   real(r8), intent(in) :: cldo(pcols,pver)
   real(r8), intent(inout) :: lcldn(pcols,pver)
   real(r8), intent(inout) :: lcldo(pcols,pver)

   integer :: i, k
   real(r8) :: qcld

         lcldn = 0._r8
         lcldo = 0._r8
         do k = top_lev, pver
            do i = 1, ncol
               qcld = qc(i,k) + qi(i,k)
               if (qcld > qsmall) then
                  lcldn(i,k) = cldn(i,k)*qc(i,k)/qcld
                  lcldo(i,k) = cldo(i,k)*qc(i,k)/qcld
               end if
            end do
         end do

  end subroutine aero_cloud_fraction_split

  subroutine aero_npccn_from_mixnuc( &
         ncol, nctend_mixnuc, npccn)

   integer,  intent(in) :: ncol
   real(r8), intent(in) :: nctend_mixnuc(pcols,pver)
   real(r8), intent(inout) :: npccn(pcols,pver)

         npccn(:ncol,:) = nctend_mixnuc(:ncol,:)

  end subroutine aero_npccn_from_mixnuc

  subroutine aero_contact_freezing( &
         ncol, top_lev, nmodes, mode_coarse_dst_idx, separate_dust, t, &
         coarse_dust, coarse_nacl, num_coarse, rho, dgnumwet, nacon, rndst)

   integer,  intent(in) :: ncol
   integer,  intent(in) :: top_lev
   integer,  intent(in) :: nmodes
   integer,  intent(in) :: mode_coarse_dst_idx
   logical,   intent(in) :: separate_dust
   real(r8), intent(in) :: t(pcols,pver)
   real(r8), intent(in) :: coarse_dust(pcols,pver)
   real(r8), intent(in) :: coarse_nacl(pcols,pver)
   real(r8), intent(in) :: num_coarse(pcols,pver)
   real(r8), intent(in) :: rho(pcols,pver)
   real(r8), intent(in) :: dgnumwet(pcols,pver,nmodes)
   real(r8), intent(inout) :: nacon(pcols,pver,4)
   real(r8), intent(inout) :: rndst(pcols,pver,4)

   integer :: i, k
   real(r8) :: dmc, ssmc, wght

      do k = top_lev, pver
         do i = 1, ncol

            if (t(i,k) < 269.15_r8) then


                  ! For modal aerosols:
                  !  use size '3' for dust coarse mode...
                  !  scale by dust fraction in coarse mode
               
                  dmc  = coarse_dust(i,k)
                  ssmc = coarse_nacl(i,k)

                  if ( separate_dust ) then
                     ! 7-mode -- has separate dust and seasalt mode types and no need for weighting 
                     wght = 1._r8
                  else
                     ! 3-mode -- needs weighting for dust since dust and seasalt are combined in the "coarse" mode type
                     wght = dmc/(ssmc + dmc)
                  endif

                  if (dmc > 0.0_r8) then
                     nacon(i,k,3) = wght*num_coarse(i,k)*rho(i,k)
                  else
                     nacon(i,k,3) = 0._r8
                  end if

                  !also redefine parameters based on size...

                  rndst(i,k,3) = 0.5_r8*dgnumwet(i,k,mode_coarse_dst_idx)
                  if (rndst(i,k,3) <= 0._r8) then 
                     rndst(i,k,3) = rn_dst3
                  end if


            end if
         end do
      end do

  end subroutine aero_contact_freezing

end module pycam_aero_kernels
