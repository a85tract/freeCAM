  integer(c_int) function pycam_rad_view_v1(lchnk, code, ptr, ndims, extents) &
       bind(C, name='pycam_rad_view_v1') result(status)
    integer(c_int), value, intent(in) :: lchnk, code
    type(c_ptr), intent(out) :: ptr
    integer(c_int), intent(out) :: ndims
    integer(c_int64_t), intent(out) :: extents(5)
    ptr = c_null_ptr
    ndims = 0_c_int
    extents = 0_c_int64_t
    status = 1_c_int
    if (.not. chunk_ok(lchnk)) return
    if (.not. associated(host_state)) return
    status = 2_c_int
    select case (code)
    case (view_state_t)
      call view2(host_state(lchnk)%t, ptr, ndims, extents)
    case (view_state_pmid)
      call view2(host_state(lchnk)%pmid, ptr, ndims, extents)
    case (view_state_pint)
      call view2(host_state(lchnk)%pint, ptr, ndims, extents)
    case (view_state_pdel)
      call view2(host_state(lchnk)%pdel, ptr, ndims, extents)
    case (view_state_lnpint)
      call view2(host_state(lchnk)%lnpint, ptr, ndims, extents)
    case (view_state_lnpmid)
      call view2(host_state(lchnk)%lnpmid, ptr, ndims, extents)
    case (view_ptend_s)
      if (.not. allocated(rad_ptend(lchnk)%s)) return
      call view2(rad_ptend(lchnk)%s, ptr, ndims, extents)
    case (view_cam_in_lwup)
      if (.not. associated(host_cam_in(lchnk)%p)) return
      call view1(host_cam_in(lchnk)%p%lwup, ptr, ndims, extents)
    case (view_cam_in_asdir)
      if (.not. associated(host_cam_in(lchnk)%p)) return
      call view1(host_cam_in(lchnk)%p%asdir, ptr, ndims, extents)
    case (view_cam_in_asdif)
      if (.not. associated(host_cam_in(lchnk)%p)) return
      call view1(host_cam_in(lchnk)%p%asdif, ptr, ndims, extents)
    case (view_cam_in_aldir)
      if (.not. associated(host_cam_in(lchnk)%p)) return
      call view1(host_cam_in(lchnk)%p%aldir, ptr, ndims, extents)
    case (view_cam_in_aldif)
      if (.not. associated(host_cam_in(lchnk)%p)) return
      call view1(host_cam_in(lchnk)%p%aldif, ptr, ndims, extents)
    case (view_cam_out_sols)
      if (.not. associated(host_cam_out(lchnk)%p)) return
      call view1(host_cam_out(lchnk)%p%sols, ptr, ndims, extents)
    case (view_cam_out_soll)
      if (.not. associated(host_cam_out(lchnk)%p)) return
      call view1(host_cam_out(lchnk)%p%soll, ptr, ndims, extents)
    case (view_cam_out_solsd)
      if (.not. associated(host_cam_out(lchnk)%p)) return
      call view1(host_cam_out(lchnk)%p%solsd, ptr, ndims, extents)
    case (view_cam_out_solld)
      if (.not. associated(host_cam_out(lchnk)%p)) return
      call view1(host_cam_out(lchnk)%p%solld, ptr, ndims, extents)
    case (view_cam_out_flwds)
      if (.not. associated(host_cam_out(lchnk)%p)) return
      call view1(host_cam_out(lchnk)%p%flwds, ptr, ndims, extents)
    case (view_cam_out_netsw)
      if (.not. associated(host_cam_out(lchnk)%p)) return
      call view1(host_cam_out(lchnk)%p%netsw, ptr, ndims, extents)
    case (view_fsns)
      if (.not. allocated(fsns)) return
      call view1(fsns(:,lchnk), ptr, ndims, extents)
    case (view_fsnt)
      if (.not. allocated(fsnt)) return
      call view1(fsnt(:,lchnk), ptr, ndims, extents)
    case (view_flns)
      if (.not. allocated(flns)) return
      call view1(flns(:,lchnk), ptr, ndims, extents)
    case (view_flnt)
      if (.not. allocated(flnt)) return
      call view1(flnt(:,lchnk), ptr, ndims, extents)
    case (view_fsds)
      if (.not. allocated(fsds)) return
      call view1(fsds(:,lchnk), ptr, ndims, extents)
    case (view_net_flx)
      call view1(rad_net_flx(:,lchnk), ptr, ndims, extents)
    case (view_rstate_h2ovmr)
      if (.not. rstate_live) return
      call view2(python_rstate%h2ovmr, ptr, ndims, extents)
    case (view_rstate_o3vmr)
      if (.not. rstate_live) return
      call view2(python_rstate%o3vmr, ptr, ndims, extents)
    case (view_rstate_co2vmr)
      if (.not. rstate_live) return
      call view2(python_rstate%co2vmr, ptr, ndims, extents)
    case (view_rstate_ch4vmr)
      if (.not. rstate_live) return
      call view2(python_rstate%ch4vmr, ptr, ndims, extents)
    case (view_rstate_o2vmr)
      if (.not. rstate_live) return
      call view2(python_rstate%o2vmr, ptr, ndims, extents)
    case (view_rstate_n2ovmr)
      if (.not. rstate_live) return
      call view2(python_rstate%n2ovmr, ptr, ndims, extents)
    case (view_rstate_cfc11vmr)
      if (.not. rstate_live) return
      call view2(python_rstate%cfc11vmr, ptr, ndims, extents)
    case (view_rstate_cfc12vmr)
      if (.not. rstate_live) return
      call view2(python_rstate%cfc12vmr, ptr, ndims, extents)
    case (view_rstate_cfc22vmr)
      if (.not. rstate_live) return
      call view2(python_rstate%cfc22vmr, ptr, ndims, extents)
    case (view_rstate_ccl4vmr)
      if (.not. rstate_live) return
      call view2(python_rstate%ccl4vmr, ptr, ndims, extents)
    case (view_rstate_pmidmb)
      if (.not. rstate_live) return
      call view2(python_rstate%pmidmb, ptr, ndims, extents)
    case (view_rstate_pintmb)
      if (.not. rstate_live) return
      call view2(python_rstate%pintmb, ptr, ndims, extents)
    case (view_rstate_tlay)
      if (.not. rstate_live) return
      call view2(python_rstate%tlay, ptr, ndims, extents)
    case (view_rstate_tlev)
      if (.not. rstate_live) return
      call view2(python_rstate%tlev, ptr, ndims, extents)
    case default
      status = 3_c_int
      return
    end select
    status = 0_c_int
  end function pycam_rad_view_v1

