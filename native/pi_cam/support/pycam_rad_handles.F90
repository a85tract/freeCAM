  integer(c_int) function pycam_rad_ice_optics_sw_v1( &
       lchnk, tau, tau_w, tau_w_g, tau_w_f) &
       bind(C, name='pycam_rad_ice_optics_sw_v1') result(status)
    integer(c_int), value, intent(in) :: lchnk
    real(c_double), intent(inout) :: tau(nbndsw,pcols,pver), tau_w(nbndsw,pcols,pver)
    real(c_double), intent(inout) :: tau_w_g(nbndsw,pcols,pver), tau_w_f(nbndsw,pcols,pver)
    type(physics_buffer_desc), pointer :: pbuf(:)

    status = 1_c_int
    if (.not. chunk_ok(lchnk)) return
    if (.not. associated(host_state)) return
    if (.not. associated(host_pbuf2d)) return
    pbuf => pbuf_get_chunk(host_pbuf2d, lchnk)
    call get_ice_optics_sw(host_state(lchnk), pbuf, tau, tau_w, tau_w_g, tau_w_f)
    status = 0_c_int
  end function pycam_rad_ice_optics_sw_v1

