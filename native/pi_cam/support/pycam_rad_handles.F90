  integer(c_int) function pycam_rad_snow_optics_sw_v1( &
       lchnk, tau, tau_w, tau_w_g, tau_w_f) &
       bind(C, name='pycam_rad_snow_optics_sw_v1') result(status)
    integer(c_int), value, intent(in) :: lchnk
    real(c_double), intent(inout) :: tau(nbndsw,pcols,pver), tau_w(nbndsw,pcols,pver)
