  subroutine rad_heating_unscale( &
         ncol, conserve_energy, pdel, qrs, qrl)

   integer,  intent(in)    :: ncol
   logical,  intent(in)    :: conserve_energy
   real(r8), intent(in)    :: pdel(pcols,pver)
   real(r8), intent(inout) :: qrs(pcols,pver), qrl(pcols,pver)

   integer :: i, k

          ! convert radiative heating rates from Q*dp to Q for energy conservation
          if (conserve_energy) then
   !DIR$ CONCURRENT
             do k =1 , pver
   !DIR$ CONCURRENT
                do i = 1, ncol
                   qrs(i,k) = qrs(i,k)/pdel(i,k)
                   qrl(i,k) = qrl(i,k)/pdel(i,k)
                end do
             end do
          end if

  end subroutine rad_heating_unscale

  subroutine rad_theta_heating( &
         ncol, qrs, qrl, cpair, pmid, cappa, ftem)

   integer,  intent(in)  :: ncol
   real(r8), intent(in)  :: qrs(pcols,pver), qrl(pcols,pver)
   real(r8), intent(in)  :: cpair, pmid(pcols,pver), cappa
   real(r8), intent(out) :: ftem(pcols,pver)

   integer :: i, k

       ! Compute heating rate for dtheta/dt 
       do k=1,pver
          do i=1,ncol
             ftem(i,k) = (qrs(i,k) + qrl(i,k))/cpair * (1.e5_r8/pmid(i,k))**cappa
          end do
       end do

  end subroutine rad_theta_heating

  subroutine rad_heating_scale( &
         ncol, conserve_energy, pdel, qrs, qrl)

   integer,  intent(in)    :: ncol
   logical,  intent(in)    :: conserve_energy
   real(r8), intent(in)    :: pdel(pcols,pver)
   real(r8), intent(inout) :: qrs(pcols,pver), qrl(pcols,pver)

   integer :: i, k

       ! convert radiative heating rates to Q*dp for energy conservation
       if (conserve_energy) then
   !DIR$ CONCURRENT
          do k =1 , pver
   !DIR$ CONCURRENT
             do i = 1, ncol
                qrs(i,k) = qrs(i,k)*pdel(i,k)
                qrl(i,k) = qrl(i,k)*pdel(i,k)
             end do
          end do
       end if

  end subroutine rad_heating_scale

  subroutine rad_inp( &
         ncol, pmid, pint, pmidrd, pintrd, eccf)

   integer,  intent(in)  :: ncol
   real(r8), intent(in)  :: pmid(pcols,pver), pint(pcols,pverp)
   real(r8), intent(out) :: pmidrd(pcols,pver), pintrd(pcols,pverp)
   real(r8), intent(out) :: eccf

   integer  :: i, k
   real(r8) :: calday
   real(r8) :: delta

      calday = get_curr_calday()
      call shr_orb_decl (calday  ,eccen     ,mvelpp  ,lambm0  ,obliqr  , &
                         delta   ,eccf)

   !
   ! Convert pressure from pascals to dynes/cm2
   !
      do k=1,pver
         do i=1,ncol
            pmidrd(i,k) = pmid(i,k)*10.0_r8
            pintrd(i,k) = pint(i,k)*10.0_r8
         end do
      end do
      do i=1,ncol
         pintrd(i,pverp) = pint(i,pverp)*10.0_r8
      end do


  end subroutine rad_inp

