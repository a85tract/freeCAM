         tot_icld_vistau, liq_icld_vistau, ice_icld_vistau, snow_icld_vistau)

   integer,  intent(in)  :: ncol, Nnite, idx_sw_diag
   integer,  intent(in)  :: IdxNite(pcols)
   logical,  intent(in)  :: has_snow
   real(r8), intent(in)  :: fillvalue
   real(r8), intent(in)  :: c_cld_tau(nbndsw,pcols,pver), liq_tau(nbndsw,pcols,pver)
   real(r8), intent(in)  :: ice_tau(nbndsw,pcols,pver), snow_tau(nbndsw,pcols,pver)
   real(r8), intent(in)  :: cldfprime(pcols,pver)
   real(r8), intent(out) :: tot_cld_vistau(pcols,pver), tot_icld_vistau(pcols,pver)
   real(r8), intent(out) :: liq_icld_vistau(pcols,pver), ice_icld_vistau(pcols,pver)
   real(r8), intent(out) :: snow_icld_vistau(pcols,pver)

   integer :: i

             tot_icld_vistau(:ncol,:)  = c_cld_tau(idx_sw_diag,:ncol,:)
             liq_icld_vistau(:ncol,:)  = liq_tau(idx_sw_diag,:ncol,:)
             ice_icld_vistau(:ncol,:)  = ice_tau(idx_sw_diag,:ncol,:)
             if (has_snow) then
                snow_icld_vistau(:ncol,:) = snow_tau(idx_sw_diag,:ncol,:)
             endif
   	  ! multiply by total cloud fraction to get gridbox value
   	  tot_cld_vistau(:ncol,:) = c_cld_tau(idx_sw_diag,:ncol,:)*cldfprime(:ncol,:)

   	  ! add fillvalue for night columns
             do i = 1, Nnite
                 tot_cld_vistau(IdxNite(i),:)   = fillvalue
                 tot_icld_vistau(IdxNite(i),:)  = fillvalue
                 liq_icld_vistau(IdxNite(i),:)  = fillvalue
                 ice_icld_vistau(IdxNite(i),:)  = fillvalue
                 if (has_snow) then
                    snow_icld_vistau(IdxNite(i),:) = fillvalue
                 endif
             end do

