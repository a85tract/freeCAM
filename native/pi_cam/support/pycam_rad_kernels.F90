  subroutine rad_interface_temperature( &
         ncol, t, lnpint, lnpmid, lwup, stebol, tint)

   integer,  intent(in)  :: ncol
   real(r8), intent(in)  :: t(pcols,pver), lnpint(pcols,pverp), lnpmid(pcols,pver)
   real(r8), intent(in)  :: lwup(pcols), stebol
   real(r8), intent(out) :: tint(pcols,pverp)

   integer  :: i, k
   real(r8) :: dy

          do i = 1,ncol
             tint(i,1) = t(i,1)
             tint(i,pverp) = sqrt(sqrt(lwup(i)/stebol))
             do k = 2,pver
                dy = (lnpint(i,k) - lnpmid(i,k)) / (lnpmid(i,k-1) - lnpmid(i,k))
                tint(i,k) = t(i,k) - dy * (t(i,k) - t(i,k-1))
             end do
          end do

  end subroutine rad_interface_temperature

