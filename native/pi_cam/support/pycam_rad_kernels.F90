  subroutine rad_snow_blend_sw( &
         ncol, has_snow, cld, cldfsnow, snow_tau, snow_tau_w, snow_tau_w_g, &
         snow_tau_w_f, cld_tau, cld_tau_w, cld_tau_w_g, cld_tau_w_f, &
         cldfprime, c_cld_tau, c_cld_tau_w, c_cld_tau_w_g, c_cld_tau_w_f)

   integer,  intent(in)    :: ncol
   logical,  intent(in)    :: has_snow
   real(r8), intent(in)    :: cld(pcols,pver), cldfsnow(pcols,pver)
   real(r8), intent(in)    :: snow_tau(nbndsw,pcols,pver), snow_tau_w(nbndsw,pcols,pver)
   real(r8), intent(in)    :: snow_tau_w_g(nbndsw,pcols,pver), snow_tau_w_f(nbndsw,pcols,pver)
   real(r8), intent(in)    :: cld_tau(nbndsw,pcols,pver), cld_tau_w(nbndsw,pcols,pver)
   real(r8), intent(in)    :: cld_tau_w_g(nbndsw,pcols,pver), cld_tau_w_f(nbndsw,pcols,pver)
   ! Written only where has_snow; the driver sets it at 993-995 otherwise,
   ! which rad_snow_blend_lw reproduces, so this carries its value out.
   real(r8), intent(inout) :: cldfprime(pcols,pver)
   real(r8), intent(out)   :: c_cld_tau(nbndsw,pcols,pver), c_cld_tau_w(nbndsw,pcols,pver)
   real(r8), intent(out)   :: c_cld_tau_w_g(nbndsw,pcols,pver), c_cld_tau_w_f(nbndsw,pcols,pver)

   integer :: i, k

             if (has_snow) then
               ! add in snow
                do i=1,ncol
                   do k=1,pver
                      cldfprime(i,k)=max(cld(i,k),cldfsnow(i,k))
                      if(cldfprime(i,k) > 0.)then
                         c_cld_tau    (1:nbndsw,i,k)= &
                              (cldfsnow(i,k)*snow_tau    (1:nbndsw,i,k) + cld(i,k)*cld_tau    (1:nbndsw,i,k))/cldfprime(i,k)
                         c_cld_tau_w  (1:nbndsw,i,k)= &
                              (cldfsnow(i,k)*snow_tau_w  (1:nbndsw,i,k) + cld(i,k)*cld_tau_w  (1:nbndsw,i,k))/cldfprime(i,k)
                         c_cld_tau_w_g(1:nbndsw,i,k)= &
                              (cldfsnow(i,k)*snow_tau_w_g(1:nbndsw,i,k) + cld(i,k)*cld_tau_w_g(1:nbndsw,i,k))/cldfprime(i,k)
                         c_cld_tau_w_f(1:nbndsw,i,k)= &
                              (cldfsnow(i,k)*snow_tau_w_f(1:nbndsw,i,k) + cld(i,k)*cld_tau_w_f(1:nbndsw,i,k))/cldfprime(i,k)
                      else
                         c_cld_tau    (1:nbndsw,i,k)= 0._r8
                         c_cld_tau_w  (1:nbndsw,i,k)= 0._r8
                         c_cld_tau_w_g(1:nbndsw,i,k)= 0._r8
                         c_cld_tau_w_f(1:nbndsw,i,k)= 0._r8
                      endif
                   enddo
                enddo
             else
                c_cld_tau    (1:nbndsw,1:ncol,:)= cld_tau    (:,1:ncol,:)
                c_cld_tau_w  (1:nbndsw,1:ncol,:)= cld_tau_w  (:,1:ncol,:)
                c_cld_tau_w_g(1:nbndsw,1:ncol,:)= cld_tau_w_g(:,1:ncol,:)
                c_cld_tau_w_f(1:nbndsw,1:ncol,:)= cld_tau_w_f(:,1:ncol,:)
             endif

  end subroutine rad_snow_blend_sw

