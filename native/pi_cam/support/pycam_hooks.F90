  integer(c_int) function pycam_hooks_arm_v1(hook, flag) bind(C, name='pycam_hooks_arm_v1') result(status)
    ! arm (flag /= 0) or disarm one hook: the owning stage does this around its run
    integer(c_int), value, intent(in) :: hook, flag
    status = 1_c_int
    if (hook < 1 .or. hook > nhooks) return
    if (flag /= 0_c_int .and. modeled(hook)) then
      status = 3_c_int; return          ! a bound model and a Python replacement cannot share a hook
    end if
    if (flag /= 0_c_int .and. .not. can_pause(hook)) then
      status = 5_c_int; return          ! a Fortran-bound hook has no frame to hand Python
    end if
    armed(hook) = flag /= 0_c_int
    status = 0_c_int
  end function pycam_hooks_arm_v1

  integer(c_int) function pycam_hooks_bind_model_v1(hook, path, length, shadow_flag) &
       bind(C, name='pycam_hooks_bind_model_v1') result(status)
    ! load the TorchScript file at path (length bytes) and answer the hook's calls with it from
    ! now on; with shadow_flag /= 0 the model runs but the original keeps answering
    integer(c_int), value, intent(in) :: hook, length, shadow_flag
    character(kind=c_char), intent(in) :: path(*)
    character(len=4096) :: filename
    integer :: i
    integer(c_int64_t) :: w0, w1
    status = 1_c_int
    if (hook < 1 .or. hook > nhooks) return
    if (.not. has_model(hook)) then
      status = 2_c_int; return
    end if
    if (armed(hook)) then
      status = 3_c_int; return
    end if
    if (length < 1 .or. length > len(filename)) then
      status = 4_c_int; return
    end if
    filename = ' '
    do i = 1, length
      filename(i:i) = path(i)
    end do
    if (modeled(hook) .and. .not. plugged(hook)) call torch_delete(models(hook))
    plugged(hook) = .false.; plugins(hook) = c_null_funptr
    call torch_model_load(models(hook), filename(1:length), torch_kCPU)
    ! one forward on zeros now: the first step does not pay the model's warm-up
    call system_clock(w0)
    call warm_model(hook)
    call system_clock(w1)
    warm_ticks(hook) = w1 - w0
    modeled(hook) = .true.
    shadow(hook) = shadow_flag /= 0_c_int
    status = 0_c_int
  end function pycam_hooks_bind_model_v1

  integer(c_int) function pycam_hooks_unbind_model_v1(hook) bind(C, name='pycam_hooks_unbind_model_v1') result(status)
    ! release the bound model or plugin: the hook answers with the original again
    integer(c_int), value, intent(in) :: hook
    status = 1_c_int
    if (hook < 1 .or. hook > nhooks) return
    if (modeled(hook)) then
      if (.not. plugged(hook)) call torch_delete(models(hook))
      modeled(hook) = .false.
      plugged(hook) = .false.
      plugins(hook) = c_null_funptr
      shadow(hook) = .false.
    end if
    status = 0_c_int
  end function pycam_hooks_unbind_model_v1

  integer(c_int) function pycam_hooks_bind_plugin_v1(hook, plugin, shadow_flag) &
       bind(C, name='pycam_hooks_bind_plugin_v1') result(status)
    ! bind a compiled plugin (a C function of the plugin_interface, e.g. a Numba cfunc) at the
    ! hook: from now on the hook hands it the model block's arrays as pointer and extent tables
    ! and takes its outputs, with no Python in the step; shadow as for a model
    integer(c_int), value, intent(in) :: hook, shadow_flag
    type(c_funptr), value, intent(in) :: plugin
    status = 1_c_int
    if (hook < 1 .or. hook > nhooks) return
    if (.not. has_model(hook)) then
      status = 2_c_int; return
    end if
    if (armed(hook)) then
      status = 3_c_int; return
    end if
    if (modeled(hook) .and. .not. plugged(hook)) call torch_delete(models(hook))
    plugins(hook) = plugin
    plugged(hook) = .true.
    modeled(hook) = .true.
    shadow(hook) = shadow_flag /= 0_c_int
    status = 0_c_int
  end function pycam_hooks_bind_plugin_v1

  integer(c_int) function pycam_hooks_model_seconds_v1(hook, model_seconds, forward_seconds, call_seconds, &
       first_seconds, warm_seconds, original_seconds) bind(C, name='pycam_hooks_model_seconds_v1') result(status)
    ! wall seconds this rank spent in the hook's model branch, in the model's forward alone,
    ! around the whole model call as the hook sees it (prologue and epilogue included), in the
    ! first modeled call alone, in the warm-up forward at bind, and in the original on the calls
    ! a shadow model also answered
    integer(c_int), value, intent(in) :: hook
    real(c_double), intent(out) :: model_seconds, forward_seconds, call_seconds, first_seconds, warm_seconds
    real(c_double), intent(out) :: original_seconds
    integer(c_int64_t) :: rate
    model_seconds = 0.0_c_double; forward_seconds = 0.0_c_double; call_seconds = 0.0_c_double
    first_seconds = 0.0_c_double; warm_seconds = 0.0_c_double; original_seconds = 0.0_c_double
    status = 1_c_int
    if (hook < 1 .or. hook > nhooks) return
    call system_clock(count_rate=rate)
    model_seconds = real(model_ticks(hook), c_double) / real(rate, c_double)
    forward_seconds = real(forward_ticks(hook), c_double) / real(rate, c_double)
    call_seconds = real(hook_ticks(hook), c_double) / real(rate, c_double)
    first_seconds = real(first_ticks(hook), c_double) / real(rate, c_double)
    warm_seconds = real(warm_ticks(hook), c_double) / real(rate, c_double)
    original_seconds = real(original_ticks(hook), c_double) / real(rate, c_double)
    status = 0_c_int
  end function pycam_hooks_model_seconds_v1

