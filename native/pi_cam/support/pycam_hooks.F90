  subroutine hook_cldfrc_fice(ncol, t, fice, fsnow) bind(C, name='pycam_hook_cldfrc_fice_')
    ! cloud_fraction::cldfrc_fice, as its redirected callers call it; rename-references
    integer(c_int), intent(in), target :: ncol
    real(c_double), intent(in), target :: t(*)
    real(c_double), intent(out), target :: fice(*)
    real(c_double), intent(out), target :: fsnow(*)
    integer :: slot
    integer(c_int64_t) :: h0, h1
    calls(1) = calls(1) + 1_c_int64_t
    if (modeled(1)) then
      ! a TorchScript model is bound here: the image answers the call itself
      answered(1) = answered(1) + 1_c_int64_t
      call system_clock(h0)
      call model_cldfrc_fice(ncol, t, fice, fsnow)
      call system_clock(h1)
      hook_ticks(1) = hook_ticks(1) + (h1 - h0)
      if (answered(1) == 1_c_int64_t) first_ticks(1) = h1 - h0
      if (.not. shadow(1)) return
      ! shadow: the model ran for its cost alone; the original answers, and is timed too
      call system_clock(h0)
      call original_cldfrc_fice(ncol, t, fice, fsnow)
      call system_clock(h1)
      original_ticks(1) = original_ticks(1) + (h1 - h0)
      return
    end if
    if (.not. armed(1)) then
      call original_cldfrc_fice(ncol, t, fice, fsnow)
      return
    end if
    if (pycam_fiber_running_v1() == 0_c_int) then
      ! armed, yet not on the owning runner's fiber: the original answers, and the miss is counted
      missed(1) = missed(1) + 1_c_int64_t
      call original_cldfrc_fice(ncol, t, fice, fsnow)
      return
    end if
    paused(1) = paused(1) + 1_c_int64_t
    slot = 0
    frame_shapes = 0_c_int64_t
    slot = slot + 1
    frame_ptrs(slot) = c_loc(ncol)
    frame_ndims(slot) = 0_c_int
    frame_dtypes(slot) = 2_c_int
    frame_intents(slot) = 0_c_int
    slot = slot + 1
    frame_ptrs(slot) = c_loc(t(1))
    frame_ndims(slot) = 2_c_int
    frame_shapes(1:2, slot) = (/ int(16, c_int64_t), int(30, c_int64_t) /)
    frame_dtypes(slot) = 1_c_int
    frame_intents(slot) = 0_c_int
    slot = slot + 1
    frame_ptrs(slot) = c_loc(fice(1))
    frame_ndims(slot) = 2_c_int
    frame_shapes(1:2, slot) = (/ int(16, c_int64_t), int(30, c_int64_t) /)
    frame_dtypes(slot) = 1_c_int
    frame_intents(slot) = 1_c_int
    slot = slot + 1
    frame_ptrs(slot) = c_loc(fsnow(1))
    frame_ndims(slot) = 2_c_int
    frame_shapes(1:2, slot) = (/ int(16, c_int64_t), int(30, c_int64_t) /)
    frame_dtypes(slot) = 1_c_int
    frame_intents(slot) = 1_c_int
    frame_nslots = 4_c_int
    frame_ncol = int(ncol, c_int)
    paused_hook = 1
    call pycam_fiber_yield_v1(ev_needs_kernel)
    ! resumed: Python wrote the outputs (or ran the original on this frame); the call is done
    paused_hook = 0
  end subroutine hook_cldfrc_fice

  subroutine original_cldfrc_fice(ncol, t, fice, fsnow)
    use cloud_fraction, only: cldfrc_fice
    integer(c_int), intent(in) :: ncol
