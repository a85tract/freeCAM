            lq(wtrc_indices(i)) = .true.
          end do
       end if

       ! the name 'cldwat' triggers special tests on cldliq
       ! and cldice in physics_update
       call physics_ptend_init(ptend, psetcols, "cldwat", ls=.true., lq=lq)


