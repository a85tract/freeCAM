            col_type=col_type, copy_if_needed=use_subcol_microp)
       call pbuf_get_field(pbuf, concld_idx,      concld,  start=(/1,1,itim_old/), kount=(/psetcols,pver,1/), &
            col_type=col_type, copy_if_needed=use_subcol_microp)
