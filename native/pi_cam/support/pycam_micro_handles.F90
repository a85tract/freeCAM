    case (6)
      call c_f_pointer(ptr, accre_enhan, (/n1, n2/))
    case (7)
      call c_f_pointer(ptr, ast, (/n1, n2/))
    case (8)
      call c_f_pointer(ptr, alst_mic, (/n1, n2/))
    case (9)
      call c_f_pointer(ptr, aist_mic, (/n1, n2/))
    case (10)
      call c_f_pointer(ptr, tnd_qsnow, (/n1, n2/))
    case (11)
